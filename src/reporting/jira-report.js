export function buildJiraReport({
  state,
  reportVisibleSockets,
  reportRelevantAnomalies,
  diagnosticHypotheses,
  reportTopSockets,
  appVersion,
  now = () => new Date().toISOString()
}) {
  const sockets = reportVisibleSockets();
  const anomalies = reportRelevantAnomalies(sockets);
  const hypotheses = diagnosticHypotheses();
  const lines = [];
  lines.push("h1. Network Incident Report");
  lines.push(`*Source:* ${state.sourceName}`);
  lines.push(`*Generated:* ${now()}`);
  lines.push(`*Sockets:* ${sockets.length} | *Anomalies:* ${anomalies.length} | *Critical:* ${sockets.filter(s => s.risk === "critical").length}`);
  lines.push("");

  if (hypotheses.length) {
    lines.push("h2. Diagnostic Hypotheses");
    for (const hypothesis of hypotheses) {
      lines.push(`h3. ${hypothesis.severity.toUpperCase()} - ${hypothesis.title} (${Math.round((hypothesis.confidenceScore || 0) * 100)}% confidence)`);
      lines.push(hypothesis.summary);
      if (hypothesis.evidence?.length) {
        lines.push("*Evidence:*");
        hypothesis.evidence.forEach(item => lines.push(`* ${item}`));
      }
      if (hypothesis.counterEvidence?.length) {
        lines.push("*Counter-evidence:*");
        hypothesis.counterEvidence.forEach(item => lines.push(`* ${item}`));
      }
      if (hypothesis.actionableCommands?.length) {
        lines.push("*Actionable commands:*");
        lines.push("{code}");
        hypothesis.actionableCommands.forEach(command => lines.push(command));
        lines.push("{code}");
      }
      lines.push("");
    }
  }

  if (anomalies.length) {
    lines.push("h2. Top Anomalies");
    lines.push("||Severity||Socket||Title||");
    anomalies.slice(0, 15).forEach(anomaly => {
      lines.push(`|${anomaly.severity}|${anomaly.socketId}|${anomaly.title}|`);
    });
    lines.push("");
  }

  const topSockets = reportTopSockets(sockets, 5);
  if (topSockets.length) {
    lines.push("h2. Top Affected Sockets");
    lines.push("||Local||Peer||State||Send-Q||Recv-Q||RTT||");
    topSockets.forEach(socket => {
      lines.push(`|${socket.local}|${socket.peer}|${socket.state}|${socket.sendQ}|${socket.recvQ}|${socket.details?.rtt || 0}ms|`);
    });
    lines.push("");
  }

  lines.push("h2. Validation Commands");
  lines.push("{code}");
  lines.push("ss -HOntepmi --tos --cgroup --inet-sockopt -a -A all");
  if (hypotheses[0]?.commands?.length) {
    hypotheses[0].commands.slice(0, 3).forEach(command => lines.push(command));
  }
  lines.push("{code}");
  lines.push("");
  lines.push("----");
  lines.push(`_Generated by Ultimate Network Expert v${appVersion}_`);
  return lines.join("\n");
}
