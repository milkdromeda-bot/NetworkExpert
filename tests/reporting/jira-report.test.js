import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";

import { buildJiraReport } from "../../src/jira-report.js";

test("buildJiraReport renders hypotheses anomalies sockets and validation commands", () => {
  const report = buildJiraReport({
    state: { sourceName: "capture.log" },
    appVersion: "1.2.3.4",
    now: () => "2026-05-25T10:00:00.000Z",
    reportVisibleSockets: () => [
      { id: "s1", risk: "critical", local: "10.0.0.1:5000", peer: "10.0.0.2:443", state: "ESTAB", sendQ: 42, recvQ: 0, details: { rtt: 12 } }
    ],
    reportRelevantAnomalies: sockets => [
      { severity: "critical", socketId: sockets[0].id, title: "Large Send-Q" }
    ],
    diagnosticHypotheses: () => [
      {
        severity: "critical",
        title: "Possible slow consumer",
        confidenceScore: 0.84,
        summary: "Send-Q is sustained.",
        evidence: ["Send-Q over threshold"],
        counterEvidence: ["No retrans spike"],
        actionableCommands: ["ss -ti dst 10.0.0.2"],
        commands: ["sar -n DEV 1", "ss -ti", "nstat -az", "ignored fourth"]
      }
    ],
    reportTopSockets: sockets => sockets
  });

  assert.match(report, /h1\. Network Incident Report/);
  assert.match(report, /\*Source:\* capture\.log/);
  assert.match(report, /\*Generated:\* 2026-05-25T10:00:00\.000Z/);
  assert.match(report, /CRITICAL - Possible slow consumer \(84% confidence\)/);
  assert.match(report, /\* Send-Q over threshold/);
  assert.match(report, /\* No retrans spike/);
  assert.match(report, /ss -ti dst 10\.0\.0\.2/);
  assert.match(report, /\|critical\|s1\|Large Send-Q\|/);
  assert.match(report, /\|10\.0\.0\.1:5000\|10\.0\.0\.2:443\|ESTAB\|42\|0\|12ms\|/);
  assert.match(report, /sar -n DEV 1/);
  assert.match(report, /nstat -az/);
  assert.doesNotMatch(report, /ignored fourth/);
  assert.match(report, /_Generated by Ultimate Network Expert v1\.2\.3\.4_/);
});

test("main delegates Jira rendering to the extracted reporting module", () => {
  const main = readFileSync(new URL("../../src/main.js", import.meta.url), "utf8");
  assert.match(main, /import \{ buildJiraReport as buildJiraReportModel \} from "\.\/jira-report\.js";/);
  assert.match(main, /function jiraReportDependencies\(\)/);
  assert.match(main, /return buildJiraReportModel\(jiraReportDependencies\(\)\);/);
});
